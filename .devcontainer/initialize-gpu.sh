#!/usr/bin/env bash
set -euo pipefail

# initializeCommand runs on the Linux Docker host, before container creation.
CONFIG_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
OUTPUT="$CONFIG_DIR/compose.gpu.generated.yaml"
shopt -s nullglob
devices=(/dev/dri/renderD*)
if (( ${#devices[@]} == 0 )); then
    echo "GPU setup failed: no /dev/dri/renderD* devices found on the host. GPU passthrough requires Linux host render devices." >&2
    exit 1
fi

groups=$(stat -c '%g' -- "${devices[@]}" | sort -nu)
temporary=$(mktemp "$CONFIG_DIR/.compose.gpu.XXXXXX")
trap 'rm -f -- "$temporary"' EXIT
{
    echo '# Generated by initialize-gpu.sh; do not edit.'
    printf 'services:\n  dev:\n    group_add:\n'
    while IFS= read -r gid; do
        printf '      - "%s"\n' "$gid"
    done <<< "$groups"
} > "$temporary"
mv -- "$temporary" "$OUTPUT"
printf 'GPU supplementary groups: %s\n' "$(echo "$groups" | paste -sd, -)"
