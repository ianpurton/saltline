//! Compact geometric stencil lettering: shared meshes, no per-label font rasterization.
use super::mesh::Builder;
use bevy::prelude::*;
fn glyph(c: char) -> [u8; 7] {
    match c {
        'A' => [14, 17, 17, 31, 17, 17, 17],
        'B' => [30, 17, 17, 30, 17, 17, 30],
        'C' => [15, 16, 16, 16, 16, 16, 15],
        'E' => [31, 16, 16, 30, 16, 16, 31],
        'G' => [15,16,16,23,17,17,15],
        'H' => [17, 17, 17, 31, 17, 17, 17],
        'I' => [31, 4, 4, 4, 4, 4, 31],
        'L' => [16, 16, 16, 16, 16, 16, 31],
        'N' => [17, 25, 25, 21, 19, 19, 17],
        'O' => [14, 17, 17, 17, 17, 17, 14],
        'P' => [30, 17, 17, 30, 16, 16, 16],
        'R' => [30, 17, 17, 30, 20, 18, 17],
        'S' => [15, 16, 16, 14, 1, 1, 30],
        'T' => [31, 4, 4, 4, 4, 4, 4],
        'U' => [17, 17, 17, 17, 17, 17, 14],
        '0' => [14, 17, 19, 21, 25, 17, 14],
        '1' => [4, 12, 4, 4, 4, 4, 14],
        '2' => [14, 17, 1, 2, 4, 8, 31],
        '3' => [30, 1, 1, 14, 1, 1, 30],
        '4' => [2, 6, 10, 18, 31, 2, 2],
        '7' => [31, 1, 2, 4, 8, 8, 8],
        '-' => [0, 0, 0, 31, 0, 0, 0],
        _ => [0; 7],
    }
}
pub fn mesh(text: &str) -> Mesh {
    let mut b = Builder::default();
    let width = text.len() as f32 * 0.6;
    for (i, c) in text.chars().enumerate() {
        for (y, row) in glyph(c).iter().enumerate() {
            for x in 0..5 {
                if row & (1 << (4 - x)) == 0 {
                    continue;
                }
                let p = Vec3::new(
                    i as f32 * 0.6 + x as f32 * 0.1 - width * 0.5,
                    0.35 - y as f32 * 0.1,
                    0.,
                );
                b.quad([
                    p,
                    p + Vec3::X * 0.088,
                    p + Vec3::new(0.088, 0.088, 0.),
                    p + Vec3::Y * 0.088,
                ]);
            }
        }
    }
    b.finish()
}
